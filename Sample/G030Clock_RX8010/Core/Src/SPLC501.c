void lcd_rst_set(void){  HAL_GPIO_WritePin( LCD_RESET_GPIO_Port,LCD_RESET_Pin, GPIO_PIN_SET);}		// RS = 1 (Select Instruction)
void lcd_rst_clr(void){  HAL_GPIO_WritePin( LCD_RESET_GPIO_Port,LCD_RESET_Pin, GPIO_PIN_RESET);}				// RS = 0 (Select Data)
void lcd_cs_set(void){   HAL_GPIO_WritePin( LCD_CS_GPIO_Port,LCD_CS_Pin , GPIO_PIN_SET)	;}			// RW = 1 (Read)
void lcd_cs_clr(void){   HAL_GPIO_WritePin( LCD_CS_GPIO_Port,LCD_CS_Pin, GPIO_PIN_RESET);}		// RW = 0 (Write)
void lcd_A0_set(void){   HAL_GPIO_WritePin( LCD_A0_GPIO_Port,LCD_A0_Pin, GPIO_PIN_SET)	;}		// EN = 1 (Enable)
void lcd_A0_clr(void){   HAL_GPIO_WritePin( LCD_A0_GPIO_Port,LCD_A0_Pin, GPIO_PIN_RESET);}						// EN = 0 (Disable)
void lcd_wr_set(void){   HAL_GPIO_WritePin( LCD_WR_GPIO_Port,LCD_WR_Pin, GPIO_PIN_SET) ;}	  				// EN = 1 (Enable)
void lcd_wr_clr(void){   HAL_GPIO_WritePin( LCD_WR_GPIO_Port,LCD_WR_Pin, GPIO_PIN_RESET)	;}					// EN = 0 (Disable)
void lcd_rd_set(void){   HAL_GPIO_WritePin( LCD_RD_GPIO_Port,LCD_RD_Pin, GPIO_PIN_SET)  ;}					// EN = 1 (Enable)
void lcd_rd_clr(void){   HAL_GPIO_WritePin( LCD_RD_GPIO_Port,LCD_RD_Pin, GPIO_PIN_RESET) ;}						// EN = 0 (Disable)
/*********************************************************/
void delay(void)
{
  // double i;
  int i;
  for(i=0;i<1;i++)
  {
    i++;
  }
}

/**********************************************************/
void lcd_write(unsigned char data)
{
  lcd_A0_set();
  lcd_cs_clr();
  lcd_wr_clr();
  GPIOB->BSRR=(GPIOB->BSRR & 0Xff00) | data;
  lcd_wr_set();
  lcd_cs_set();
  GPIOB->BSRR = (uint32_t)0x00ff << 16U;
}		

void lcd_cmd(unsigned char control)
{
	lcd_rd_set();
  lcd_A0_clr();
  lcd_cs_clr();
  lcd_wr_clr();
  GPIOB->BSRR=(GPIOB->BSRR & 0Xff00) | control;
  lcd_wr_set();
  lcd_A0_set();	
  lcd_cs_set();
  GPIOB->BSRR = (uint32_t)0x00ff << 16U;
}
/***************************************************************/

void lcd_set_column( char cx,  char cy)
{
  lcd_cmd((cx) & 0x0f);
  lcd_cmd((((cx) & 0xf0) >> 4) | 0x10);
  lcd_cmd((cy & 0x0f) | 0xb0);
  return;
}

/***********************************************************/
void lcd_set_cursor(unsigned char cx, unsigned char cy)
{
  cursorx = cx;
  cursory = cy;
  lcd_set_column(cx*6, cy*1);
}
/************************************************************/
void lcd_char (char ch)
{
  unsigned int ptr;
  int q;
  lcd_set_cursor(cursorx, cursory);      
  ptr = (unsigned int)(((ch - 0x20)*10)+1);                  // point to low byte of font data
  
  for (q = 0; q < 5; q++){
    lcd_write(0x02);
    ptr+=2;
  }
  lcd_write(0);                                                      // the space between the words
  ptr = (unsigned int)(((ch - 0x20)*10));                  // point to high byte of font data
  lcd_set_column(cursorx*6, (cursory*2)+1);
  for (q = 0; q < 5; q++)
  {
    lcd_write(font[ptr]);
    ptr+=2;
  }
  lcd_write(0);
  cursorx++;
  if (cursorx == 20)
  {
    cursorx = 0;
    cursory++;
  }
  if (cursory > 3)
    cursory = 0;
}

/***********************************************************************/
void lcd_cls (void)
{
  int r, q;
  for (r=0; r<=8; r++)
  {
    lcd_set_column(0,r);      // set_column adds 4 to the position
    for (q=0; q<132; q++) 
    {
      lcd_write(0x0);
    }
  }
}
/**********************************************************************/

/***********************************************************************/
void lcd_init(void)

{
  lcd_wr_set();	 
  lcd_A0_set();  
  lcd_cs_set();  
  
  lcd_rd_set();
  lcd_rst_clr();
  HAL_Delay(50);
  lcd_rst_set();
  HAL_Delay(50);
  

  lcd_cmd(0xA0);      // <- ADC Direction L-R
  lcd_cmd(0xC8);      // <- SHL Direction 0-64
  lcd_cmd(0xA2);      // <- Voltage ref
  lcd_cmd(0x2C); // voltage converter on
  HAL_Delay(1);
  lcd_cmd(0x2E); // voltage regulator on
  
  HAL_Delay(1);
  
  lcd_cmd(0x2F); // voltage follower on
  lcd_cmd(0x27); // regulator resistor
  lcd_cmd(0x81); // set reference voltage 
  lcd_cmd(0x10); // reference voltage value (contraste)
  lcd_cmd(0xAF); // DiSP ON 
	lcd_cls();
  lcd_cmd(0xA5); // all on
  HAL_Delay(500);
  lcd_cmd(0xA4); // all off
}



/************************************************************/
void lcd_print (char * text)
{
  int q;
  // print a string to the lcd
  for (q=0; q<strlen(text); q++)
  {
    lcd_char(text[q]);
  }
}


