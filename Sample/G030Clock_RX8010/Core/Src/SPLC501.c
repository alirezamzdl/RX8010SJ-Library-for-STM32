void LCD_write_char_Medium (unsigned char X,unsigned char Y, unsigned char ch, char mode)
{
  unsigned char i, j;
  unsigned char ch_dat;
//  if(ch == ' ')
//    ch = 13;
//  else
//    ch = ch - 0x2d;
//
  // New character mapping with % support
  if (ch == '-')        ch = 0;
  else if (ch == '.')   ch = 1;
  else if (ch == '%')   ch = 2;        // <‑‑ NEW
  else if (ch == '/')   ch = 3;
  else if (ch == ':')   ch = 4;
  else if (ch >= '0' && ch <= '9')
      ch = 5 + (ch - '0');             // 0..9  → 4..13
  else if (ch == ' ')
      ch = 15;
  else
      return; // unsupported character

  for(i=0;i<2;i++)
  {	
    lcd_set_column ( X, Y+i);
    for(j=0; j<11; j++){
      
      ch_dat = MediumNumbers[(ch*24) + (i*12) +j];
      lcd_write((mode == 0)? ch_dat : (ch_dat^0xff));
    }}}

void LCD_write_string_Medium ( unsigned char X,unsigned char Y, char *string, char mode )
{
  while ( *string ){
    LCD_write_char_Medium( X, Y, *string , mode);
    if(*string++ == '.')
      X += 4;
    else
      X += 12;
  }}


