void LcdCharacter(char character){
  lcd_write(0x00);
  for (int index = 0; index < 5; index++)
  {lcd_write( ASCII[character - 0x20][index]);
  }}

void LcdString(char *characters){
  while (*characters){
    LcdCharacter(*characters++);
  }
}

void LcdCharacter_neg(char character){
  lcd_write(0xff);
  for (int index = 0; index < 5; index++)
  {lcd_write( 0xff - ASCII[character - 0x20][index]);
  }}


void LcdString_neg(char *characters, uint8_t neg){
  if (neg==1){
    while (*characters){
      LcdCharacter_neg(*characters++);
    }
  }
  else {
    while (*characters){
      LcdCharacter(*characters++);
    }
  }
  
}



void draw_progbar(int value,int row){
  int index;
  if(value>72)value=72;
  lcd_set_column(0,row);
  lcd_write(0xff);
  lcd_write(0x81);
  for (index = 0; index < 72; index++)
  {if (index<value)lcd_write(0xbd);
  else lcd_write(0x81);
  }
  lcd_write(0x81);
  lcd_write(0xff);
}



